/**
 * Mengambil data Titik Lintas Kustom berdasarkan Shape, Flange, dan Total Points,
 * kemudian menghitung jarak (cm) secara dinamis.
 * Formula CM: Jarak (cm) = (Persen / 100) * Diameter (m) * 100
 * Simplifikasi: Jarak (cm) = Persen * Diameter (m)
 * * @returns {Array<{tl: number, percent: number, cm: number}> | null}
 */
export const calculateFinalPoints = (
  shape: string,
  flange: string,
  totalPoints: number,
  diameter: number,
  flangeSizeParam: string,
  lookupTable: ShapeData = hierarchicalPointData
): { tl: string; percent: number; cm: number }[] | null => {
  if (totalPoints <= 0 || !shape || !flange || diameter <= 0) {
    return null;
  }

  try {
    const pointsData = lookupTable[shape]?.[flange]?.[totalPoints];

    if (pointsData && pointsData.length > 0) {
      const flangeSize =
        parseFloat((flangeSizeParam || "0").replace(",", ".")) || 0;
        
      // finalData DIDEFINISIKAN DAN DIGUNAKAN DI SINI
      const finalData = pointsData.map((item) => {
        const cmValue = item.percent * diameter + flangeSize;

        return {
          tl: item.tl,
          percent: item.percent,
          cm: cmValue,
        };
      });

      return finalData; // <-- return berhasil di sini
    }
  } catch (e) {
    console.error("Lookup data kustom gagal:", e);
    return []; // Pastikan ini mengembalikan Array kosong jika error
  }

  // Jika data tidak ditemukan (misalnya, totalPoints tidak ada)
  return []; // Pastikan ini mengembalikan Array kosong
};
